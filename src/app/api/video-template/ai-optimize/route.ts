export async function POST(req: NextRequest) {
  try {
    const body = await req.json().catch(() => ({}));
    const {
      currentLayers = {},
      activeRatio = "16:9",
      templateName = "",
      animationStyle = "dynamic_retail",
      bgColor = "#0B2830",
    } = body;

    // Generate balanced, professional commercial layouts for all 4 ratios
    const aspectStore = generateOptimizedLayouts(currentLayers, {
      templateName,
      animationStyle,
      bgColor,
    });

    return NextResponse.json({
      success: true,
      aspectStore,
      message: "All 4 aspect ratios optimized successfully with AI commercial design rules.",
    });
  } catch (error: any) {
    console.error("[POST /api/video-template/ai-optimize] Error:", error);
    return NextResponse.json(
      { success: false, message: error?.message || "Failed to optimize template ratios" },
      { status: 500 }
    );
  }
}
